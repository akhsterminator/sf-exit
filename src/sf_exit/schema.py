"""Turn Salesforce describe metadata into SQL DDL and an entity-relationship diagram."""

from __future__ import annotations

from typing import Any, Dict, Iterable, List, Optional

DIALECTS = ("postgres", "duckdb", "sqlite")

# Salesforce field type -> SQL type per dialect
_TYPES: Dict[str, Dict[str, str]] = {
    "postgres": {
        "id": "VARCHAR(18)",
        "reference": "VARCHAR(18)",
        "boolean": "BOOLEAN",
        "int": "BIGINT",
        "long": "BIGINT",
        "double": "DOUBLE PRECISION",
        "currency": "NUMERIC",
        "percent": "NUMERIC",
        "date": "DATE",
        "datetime": "TIMESTAMPTZ",
    },
    "duckdb": {
        "id": "VARCHAR",
        "reference": "VARCHAR",
        "boolean": "BOOLEAN",
        "int": "BIGINT",
        "long": "BIGINT",
        "double": "DOUBLE",
        "currency": "DOUBLE",
        "percent": "DOUBLE",
        "date": "DATE",
        "datetime": "TIMESTAMPTZ",
    },
    "sqlite": {
        "id": "TEXT",
        "reference": "TEXT",
        "boolean": "INTEGER",
        "int": "INTEGER",
        "long": "INTEGER",
        "double": "REAL",
        "currency": "REAL",
        "percent": "REAL",
        "date": "TEXT",
        "datetime": "TEXT",
    },
}
_DEFAULT = {"postgres": "TEXT", "duckdb": "VARCHAR", "sqlite": "TEXT"}


def sql_type(sf_type: str, dialect: str) -> str:
    return _TYPES[dialect].get(sf_type, _DEFAULT[dialect])


def quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def table_name(sobject: str, lowercase: bool = False) -> str:
    return sobject.lower() if lowercase else sobject


def create_table_sql(
    sobject: str,
    columns: List[str],
    field_types: Dict[str, str],
    dialect: str,
    lowercase: bool = False,
    if_not_exists: bool = True,
) -> str:
    lines = []
    for col in columns:
        ctype = sql_type(field_types.get(col, "string"), dialect)
        cname = col.lower() if lowercase else col
        pk = " PRIMARY KEY" if col == "Id" else ""
        lines.append(f"  {quote_ident(cname)} {ctype}{pk}")
    ine = "IF NOT EXISTS " if if_not_exists else ""
    body = ",\n".join(lines)
    return f"CREATE TABLE {ine}{quote_ident(table_name(sobject, lowercase))} (\n{body}\n);"


def references(describe: Dict[str, Any]) -> Iterable[tuple]:
    """Yield (field, [target objects]) for every lookup / master-detail field."""
    for f in describe.get("fields", []):
        if f.get("type") == "reference" and f.get("referenceTo"):
            yield f["name"], list(f["referenceTo"]), bool(f.get("cascadeDelete"))


def schema_sql(
    plans: Dict[str, Any], dialect: str, lowercase: bool = False, comment: Optional[str] = None
) -> str:
    """Full DDL script for every exported object, with relationships documented as comments.

    Foreign-key constraints are not emitted on purpose: Salesforce lookups are often
    polymorphic (WhoId, WhatId, OwnerId...) and point at objects you may not have exported.
    """
    out = []
    if comment:
        out.append(f"-- {comment}")
    out.append(f"-- Dialect: {dialect}. Generated by sf-exit. Load data with `sf-exit load`.\n")
    for name in sorted(plans, key=str.lower):
        plan = plans[name]
        out.append(
            create_table_sql(name, plan.fields, plan.field_types, dialect, lowercase=lowercase)
        )
        refs = [r for r in references(plan.describe) if r[0] in plan.fields]
        for field, targets, _ in refs:
            out.append(f"-- {name}.{field} -> {' | '.join(targets)}.Id")
        out.append("")
    return "\n".join(out)


def mermaid_erd(plans: Dict[str, Any], only_nonempty: Optional[Dict[str, int]] = None) -> str:
    """Mermaid ER diagram of relationships between exported objects (GitHub renders these)."""
    names = set(plans)
    if only_nonempty is not None:
        names = {n for n in names if only_nonempty.get(n, 0) > 0}
    lines = ["erDiagram"]
    edges = set()
    noisy = {"CreatedById", "LastModifiedById", "OwnerId"}
    for name in sorted(names):
        for field, targets, master in references(plans[name].describe):
            if field in noisy:
                continue
            for target in targets:
                if target in names and target != name:
                    rel = "}|--||" if master else "}o--o|"
                    edges.add(f'  {_mm(name)} {rel} {_mm(target)} : "{field}"')
    lines.extend(sorted(edges))
    return "\n".join(lines) + "\n"


def _mm(name: str) -> str:
    return name.replace("__", "_")
